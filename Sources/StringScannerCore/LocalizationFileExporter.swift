import Foundation

public enum LocalizationExportScope: String, Sendable, Codable, CaseIterable {
    /// Non-localized user-facing strings (default for building a new catalog).
    case unlocalizedOnly
    /// Every unique string content from the scan.
    case all
    /// Strings already marked localized (e.g. to seed/rebuild catalogs from code keys).
    case localizedOnly
}

public enum LocalizationFileExporter {
    /// Unique keys suitable for Localizable tables, preserving first-seen comment location.
    public static func localizationEntries(
        from results: [StringLocation],
        scope: LocalizationExportScope = .unlocalizedOnly
    ) -> [(key: String, comment: String)] {
        var seen = Set<String>()
        var entries: [(key: String, comment: String)] = []

        for result in results {
            switch scope {
            case .unlocalizedOnly:
                guard !result.isLocalized else { continue }
            case .localizedOnly:
                guard result.isLocalized else { continue }
            case .all:
                break
            }

            // Skip empty / non-copy noise unless caller asked for everything.
            if scope != .all {
                guard result.kind == .copy || result.kind == .format else { continue }
            }

            let key = result.content
            guard !key.isEmpty, seen.insert(key).inserted else { continue }
            let fileName = URL(fileURLWithPath: result.file).lastPathComponent
            let comment = "\(fileName):\(result.line)"
            entries.append((key: key, comment: comment))
        }

        return entries.sorted { $0.key.localizedStandardCompare($1.key) == .orderedAscending }
    }

    public static func makeStringsFile(
        from results: [StringLocation],
        scope: LocalizationExportScope = .unlocalizedOnly
    ) -> String {
        let entries = localizationEntries(from: results, scope: scope)
        var lines: [String] = [
            "/* Generated by StringScanner */",
            ""
        ]
        for entry in entries {
            lines.append("/* \(entry.comment) */")
            lines.append("\"\(escapeStrings(entry.key))\" = \"\(escapeStrings(entry.key))\";")
            lines.append("")
        }
        return lines.joined(separator: "\n")
    }

    public static func makeXCStringsData(
        from results: [StringLocation],
        scope: LocalizationExportScope = .unlocalizedOnly,
        sourceLanguage: String = "en"
    ) throws -> Data {
        let entries = localizationEntries(from: results, scope: scope)
        var strings: [String: Any] = [:]

        for entry in entries {
            strings[entry.key] = [
                "comment": entry.comment,
                "extractionState": "manual",
                "localizations": [
                    sourceLanguage: [
                        "stringUnit": [
                            "state": "new",
                            "value": entry.key
                        ]
                    ]
                ]
            ] as [String: Any]
        }

        let root: [String: Any] = [
            "sourceLanguage": sourceLanguage,
            "version": "1.0",
            "strings": strings
        ]

        return try JSONSerialization.data(withJSONObject: root, options: [.prettyPrinted, .sortedKeys])
    }

    private static func escapeStrings(_ value: String) -> String {
        value
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
            .replacingOccurrences(of: "\n", with: "\\n")
            .replacingOccurrences(of: "\t", with: "\\t")
    }
}
